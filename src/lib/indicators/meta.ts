/** 按主题分组指标 */
export function groupByTheme(): Map<string, IndicatorMeta[]> {
  const map = new Map<string, IndicatorMeta[]>();
  for (const m of INDICATOR_META) {
    const list = map.get(m.theme) ?? [];
    list.push(m);
    map.set(m.theme, list);
  }
  return map;
}
