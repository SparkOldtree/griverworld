// 宏观指标元数据（中国/美国）
// 采集配置与展示元数据统一维护，采集脚本（scripts/fetch-indicators.mjs）与前端共用

export type Region = 'CN' | 'US';
export type Direction = 'up_good' | 'down_good' | 'neutral';
export type IndicatorStatus = 'active' | 'pending';

export interface FetchConfig {
  /** cn_report: 东方财富中国报表; cn_rate: 东方财富利率报表（如 LPR）; us_indicator: 东方财富美国指标库; fred: FRED CSV（日/月频，取月末值）; cn_kline: 东方财富行情 K 线（日频，取月末值） */
  kind: 'cn_report' | 'cn_rate' | 'us_indicator' | 'fred' | 'cn_kline' | null;
  /** cn: 报表名; us: INDICATOR_ID; fred: FRED 序列号; kline: secid */
  ref: string;
  /** cn: 取值字段名 */
  field?: string;
  /** 数值单位换算系数（乘以此系数转为展示单位） */
  unitMult?: number;
  /** 特殊计算 */
  calc?: 'gdp_annualized' | 'div_10' | 'div_100';
  /** 数据异常的日期（YYYY-MM），采集时强制置空不展示 */
  exclude?: string[];
}

export interface IndicatorMeta {
  code: string;
  region: Region;
  regionName: string;
  /** 指标名（展示用） */
  name: string;
  /** 短名（热力图坐标轴用） */
  shortName: string;
  /** 跨地区对比主题（同主题不同地区可对比，如 GDP 主题 = CN_GDP + US_GDP） */
  theme: string;
  /** 主题名（对比图用） */
  themeName: string;
  category: string;
  unit: string;
  direction: Direction;
  /** 颜色映射中心值（如 PMI=50、同比=0） */
  neutral: number;
  status: IndicatorStatus;
  agency: string;
  frequency: string;
  /** 发布滞后说明 */
  lag: string;
  definition: string;
  note: string;
  fetch: FetchConfig;
}

